#!/usr/bin/env node
// Pipeline step 4: tests the video's WORLD before there are scenes (no voice needed).
//   usage: node core/world.ts videos/<topic> [--preview]
//   reads  videos/<topic>/world.json  the test shots:
//          { "style": "3d", "shots": [ { "id": "test-hero", "title": "Hero: every state", "duration": 4, "snap": [0.5, 2, 3.5],
//                                        "keys": [ { "id": "jump", "t": 1.5 } ] } ] }
//          (duration, snap and keys in seconds FROM THE SHOT'S START; snap: the moments to capture, default one at 62%)
//   and    the world file (world3d.ts in 3d, world.ts in flat2d): the reusable pieces, plus one defineVisuals entry per test shot
//   writes videos/<topic>/world.png (numbered panels) and world.md (panel -> shot, time, title)
//   --preview opens the live preview with the world test, to watch it moving.
// The test is built in videos/<topic>/world/ (regenerated each time): a silent video whose scenes are the test shots.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './style.ts';
import type { Plan, Scene } from './types.ts';

interface Shot { id: string; title?: string; highlight?: string; label?: string; duration: number; snap?: number[]; keys?: { id: string; t: number }[] }
const argv = process.argv.slice(2);
if (!argv[0] || argv[0].startsWith('--')) { console.error('usage: node core/world.ts videos/<topic> [--preview]'); process.exit(2); }
const v = path.resolve(argv[0]), wf = path.join(v, 'world.json');
if (!fs.existsSync(wf)) { console.error(`there is no ${path.join(argv[0], 'world.json')} (the test shots of the world)`); process.exit(1); }
const W: { style: string; fps?: number; shots: Shot[] } = JSON.parse(fs.readFileSync(wf, 'utf8'));
const WORLD_FILE: Record<string, string> = { '3d': 'world3d.ts', flat2d: 'world.ts' };
const file = WORLD_FILE[W.style];
const err: string[] = [];
if (!file) err.push(`style "${W.style}" has no world file (${Object.entries(WORLD_FILE).map(([s, f]) => `${s}: ${f}`).join(', ')})`);
else if (!fs.existsSync(path.join(v, file))) err.push(`there is no ${path.join(argv[0], file)}`);
if (!W.shots?.length) err.push('world.json has no shots');
for (const s of W.shots || []) {
  if (!(s.duration > 0)) err.push(`${s.id}: needs "duration" in seconds`);
  for (const t of s.snap || []) if (t < 0 || t >= s.duration) err.push(`${s.id}: snap ${t}s is outside the shot (0–${s.duration}s)`);
  for (const k of s.keys || []) if (k.t < 0 || k.t >= s.duration) err.push(`${s.id}.${k.id}: key ${k.t}s is outside the shot (0–${s.duration}s)`);
}
if (err.length) { for (const e of err) console.log('  ERROR  ', e); process.exit(1); }

// the test as a silent video: one scene per shot, times made absolute
const tmp = path.join(v, 'world'); fs.rmSync(tmp, { recursive: true, force: true }); fs.mkdirSync(tmp, { recursive: true });
let t = 0; const times: number[] = [], rows: string[] = [];
const scenes = W.shots.map((s) => {
  const t0 = +t.toFixed(3); t += s.duration;
  const snaps = s.snap?.length ? s.snap : [s.duration * 0.62];
  for (const x of snaps) { times.push(+(t0 + x).toFixed(2)); rows.push(`| ${rows.length + 1} | ${s.id} | ${x} | ${s.title || ''} |`); }
  return { id: s.id, type: 'object', label: s.label ?? 'World test', title: s.title, highlight: s.highlight, keys: (s.keys || []).map((k) => ({ id: k.id, t: +(t0 + k.t).toFixed(3) })), t0, t1: 0 } as Scene;
});
const plan: Plan = { style: W.style, fps: W.fps ?? 30, format: '9:16', duration: +t.toFixed(3), notes: 'World test (generated by core/world.ts from world.json)', scenes };
fs.writeFileSync(path.join(tmp, 'scenes.json'), JSON.stringify(plan, null, 1));
fs.copyFileSync(path.join(v, file!), path.join(tmp, file!));
if (fs.existsSync(path.join(v, 'theme.css'))) fs.copyFileSync(path.join(v, 'theme.css'), path.join(tmp, 'theme.css'));
if (fs.existsSync(path.join(v, 'assets'))) fs.cpSync(path.join(v, 'assets'), path.join(tmp, 'assets'), { recursive: true });
const node = (script: string, ...a: string[]) => { const r = spawnSync(process.execPath, [path.join(ROOT, 'core', script), ...a], { stdio: 'inherit' }); if (r.status !== 0) process.exit(r.status || 1); };
node('scenes.ts', tmp);   // stamps t1 and checks the contract (keys away from the cuts, etc.)
node('storyboard.ts', tmp, '--times', times.join(','));
fs.renameSync(path.join(tmp, 'storyboard.png'), path.join(v, 'world.png'));
fs.writeFileSync(path.join(v, 'world.md'), `# World test: ${path.basename(v)} (${W.style})\n\n![world test](world.png)\n\n| panel | shot | t in the shot (s) | what it tests |\n|---|---|---|---|\n${rows.join('\n')}\n`);
console.log(`world test: ${times.length} panels -> ${path.join(argv[0], 'world.png')} (+ world.md)`);
if (argv.includes('--preview')) node('preview.ts', tmp);
